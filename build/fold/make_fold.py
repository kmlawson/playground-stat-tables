"""Write fold.js (site root): groups of equivalent CJK character forms so searches match across
traditional / simplified Chinese and Japanese kyūjitai / shinjitai (總 総 总, 說 説 说, 敎 教 …).

Source: OpenCC dictionaries (Apache-2.0), saved here: STCharacters, TSCharacters, JPShinjitaiCharacters,
TWVariants, HKVariants. Run: python3 build/fold/make_fold.py
"""
import os, json
HERE = os.path.dirname(os.path.abspath(__file__))
parent = {}


def find(c):
    while parent.setdefault(c, c) != c:
        parent[c] = parent[parent[c]]
        c = parent[c]
    return c


def union(a, b):
    ra, rb = find(a), find(b)
    if ra != rb:
        parent[rb] = ra


for name in ("TSCharacters", "STCharacters", "JPShinjitaiCharacters", "TWVariants", "HKVariants"):
    with open(os.path.join(HERE, name + ".txt"), encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#") or "\t" not in line:
                continue
            k, v = line.rstrip("\n").split("\t", 1)
            for x in [k] + v.split():
                if len(x) == 1 and len(k) == 1 and ord(x) < 0x10000 and ord(k) < 0x10000:  # BMP only: keeps UTF-16 length
                    union(k, x)
groups = {}
for c in parent:
    groups.setdefault(find(c), []).append(c)
groups = ["".join(sorted(g)) for g in groups.values() if len(g) > 1]
groups.sort()
js = ("// Generated by build/fold/make_fold.py from OpenCC character tables (Apache-2.0).\n"
      "// Equivalent CJK forms (traditional/simplified Chinese, Japanese kyūjitai/shinjitai) for search.\n"
      f"const FOLD_GROUPS={json.dumps('|'.join(groups), ensure_ascii=False)};\n"
      "const FOLD=new Map(),FOLDG=new Map();FOLD_GROUPS.split(\"|\").forEach(g=>{const a=[...g];a.forEach(c=>{FOLD.set(c,a[0]);FOLDG.set(c,g)})});\n"
      "function fold(s){let o=\"\";for(const c of String(s??\"\"))o+=FOLD.get(c)||c;return o}\n"
      "function foldRe(w){return [...w].map(c=>{const g=FOLDG.get(c);return g?\"[\"+g+\"]\":c.replace(/[.*+?^${}()|[\\]\\\\]/g,\"\\\\$&\")}).join(\"\")}\n")
with open(os.path.join(HERE, "..", "..", "fold.js"), "w", encoding="utf-8") as fh:
    fh.write(js)
print(len(groups), "groups,", sum(len(g) for g in groups), "characters")
